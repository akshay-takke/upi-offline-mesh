CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(30) NOT NULL UNIQUE,
    account_holder_name VARCHAR(100) NOT NULL,
    balance NUMERIC(19, 2) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_account_balance CHECK ( balance >= 0 ),
    CONSTRAINT chk_account_status
        CHECK ( status IN ('ACTIVE', 'BLOCKED', 'CLOSED'))
);

CREATE TABLE payment_instructions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instruction_id UUID NOT NULL UNIQUE,
    sender_id BIGINT NOT NULL REFERENCES accounts(id),
    receiver_id BIGINT NOT NULL REFERENCES accounts(id),
    amount NUMERIC(19, 2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'CREATED',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,

    CONSTRAINT chk_instruction_amount CHECK ( amount > 0 ),
    CONSTRAINT chk_different_accounts CHECK ( sender_id <> receiver_id ),
    CONSTRAINT chk_instruction_status CHECK (
        status IN (
            'CREATED', 'IN_TRANSIT', 'PENDING',
                  'SETTLED', 'REJECTED', 'EXPIRED'
            )
        ),
    CONSTRAINT chk_instruction_expiry CHECK ( expires_at > created_at )
);

CREATE TABLE transactions
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id         UUID           NOT NULL UNIQUE,
    payment_instruction_id BIGINT         NOT NULL UNIQUE
        REFERENCES payment_instructions (id),
    amount                 NUMERIC(19, 2) NOT NULL,
    status                 VARCHAR(20)    NOT NULL,
    settled_at             TIMESTAMP,

    CONSTRAINT chk_transaction_amount CHECK ( amount > 0 ),
    CONSTRAINT chk_transaction_status
        CHECK ( status IN ('PENDING', 'SETTLED', 'FAILED'))
);

CREATE INDEX idx_payment_sender ON payment_instructions(sender_id);

CREATE INDEX idx_payment_receiver ON payment_instructions(receiver_id);

CREATE INDEX idx_payment_status ON payment_instructions(status);
